"""Repeatable local audit; reads originals, writes only derived docs/runtime files."""
from pathlib import Path
import csv
import hashlib
import json
import sys
from collections import Counter

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.backend.app.ingest import load_case, write_normalized_cache


def main():
    with (ROOT / "Dataset/registro_rinomine.csv").open(encoding="utf-8-sig") as f:
        originals = list(csv.DictReader(f))
    mismatches = [r["percorso_italiano"] for r in originals
                  if not (ROOT/r["percorso_italiano"]).is_file() or
                  hashlib.sha256((ROOT/r["percorso_italiano"]).read_bytes()).hexdigest() != r["sha256"]]
    if mismatches:
        raise SystemExit(f"Original integrity check FAILED: {mismatches}")
    lines = ["# Data audit — actual local inputs", "", "Generated by `python scripts/audit_data.py`. No original file is changed.", "",
             f"Integrity: **{len(originals)}/{len(originals)} original SHA-256 values match** the rename register.",
             f"Original size: {sum((ROOT/r['percorso_italiano']).stat().st_size for r in originals):,} bytes.",
             "", "## Selected primary case", "", "Iskar at Novi Iskar. Orehovitsa is independently selectable, never spliced into the Novi Iskar series. Arda is the documented alternative narrative only if the primary dataset proves unusable; the Iskar files are usable, so no reservoir-operation rules or cross-year joins are added.",
             "", "## Station audits", ""]
    for case_id in ("iskar-novi", "iskar-orehovitsa"):
        case=load_case(case_id)
        write_normalized_cache(case)
        summary=case["summary"]
        lines.extend([f"### {case['station']['name']}", "", f"- Verified path: `{case['source']['path']}`",
                      f"- SHA-256: `{case['source']['sha256']}`",
                      f"- Rows: {summary['rows']}; calendar days: {summary['calendar_days']}; duplicate dates: {summary['duplicates']}.",
                      f"- Period: {' to '.join(case['source']['period'])}.",
                      "- Observed columns: `date`, `discharge(m3/s)`. Variable: discharge, not water level.",
                      f"- Value range: {summary['minimum']}–{summary['maximum']} m3/s; median: {summary['median']} m3/s.",
                      f"- Missing dates ({len(summary['missing_days'])}): {', '.join(summary['missing_days'])}.",
                      "- No interpolation or missing-value substitution. Missing dates remain null timeline points.",
                      "- Negative values are suspect; duplicate dates are retained, flagged and withheld from classification.",
                      "- Station identity: local catalogue + source filename only; original gauge ID, coordinates and municipal crosswalk unavailable.",
                      f"- {case['source']['time_note']}",
                      f"- License: {case['source']['license']}.", "", "Representative original rows:", "",
                      "| CSV row | Date | Raw value | Canonical unit | Mode |", "|---:|---|---|---|---|"])
        for row in [case["observations"][0], next(o for o in case["observations"] if o["date"]=="2025-09-25"),case["observations"][-1]]:
            lines.append(f"| {row['source_row']} | {row['date']} | {row['raw_value']} | {row['unit']} | historical |")
        lines.append("")
    lines.extend(["## Other local categories — not used as event evidence", "", "| Category | Actual formats excluding README | Limitation |", "|---|---|---|"])
    notes={"Cascade Arda":"Legacy XLS, 2017. Requires reservoir-specific units, formula review and references; no mandated gate operations inferred.",
           "Danube":"2021, different stations and periods; blank, repeated and text-valued rows need an independent adapter.",
           "cds_output":"2024 climate grids. Aggregation/masks require checking; not simultaneous rainfall for Iskar 2025.",
           "gee_output":"2024 and March–April 2026. Units/product/aggregation incomplete; no operational overlay.",
           "groundwater Bulgaria":"2018–2024 chemistry; no station ID or coordinates. No spatial crosswalk or flood alert.",
           "surfacewater Bulgaria_best":"2019–2024 chemistry; best is not a water-quality class; station identity absent.",
           "surfacewater Bulgaria_weak":"2019–2024 chemistry; weak is not a pollution class; station identity absent.",
           "Fishing Black Sea":"Fleet reports, no flood-relevant sensor observations; excluded."}
    for folder,note in notes.items():
        counts=Counter(p.suffix for p in (ROOT/"Dataset"/folder).rglob("*") if p.is_file() and p.suffix!=".md")
        lines.append(f"| `{folder}` | {', '.join(f'{n} {ext}' for ext,n in sorted(counts.items()))} | {note} |")
    lines.extend(["", "## Scientific and packaging limits", "",
                  "The UTC timestamp is a canonical representation of a date-only record, not proof of sampling time. No live observations, quantitative rainfall-discharge relationship, wave travel time, inundation footprint, damage estimate, calibrated forecast or probability is available.", "",
                  "Thresholds 8/20/50 and alternate 15/35/70 m3/s are explicit DEMO_CONFIG values chosen after inspecting the observed range. They are not official thresholds. Synthetic values use anchor + daily increase × whole-day step; they are never labelled as measurements.", "",
                  "Original data remains local and gitignored. No redistributable real-data sample is bundled because redistribution rights are not established. The normalized cache is ignored under runtime/. Application errors never substitute a synthetic observation for a missing source.", "",
                  "The confidential event PDF is not opened by the pipeline and is not served or bundled. The mockup is a layout reference only."])
    (ROOT/"docs/DATA_AUDIT.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    print(json.dumps({"original_hashes_matched":len(originals),"cases":2,"audit":"docs/DATA_AUDIT.md","originals_modified":False}))


if __name__=="__main__":
    main()
